"""ACE target detection of roofs like library candidate #14, and a blind check sheet.

Course notebook 14 (section 3) on our EnMAP scene:
1. Target: candidate #14, a large bright roof that looks like metal (docs/spectral_library).
   Its 3 x 3 pixels are one roof: 4 make the signature, the other 5 are implanted.
2. Implantation benchmark (SAM, matched filter, CEM, ACE) -> docs/ace/implantation.csv.
3. ACE over the model area with the full 9-pixel signature; detections are the top 0.2 % of
   background scores (the course's threshold), grouped into sites.
4. Blind check sheet: the sites with >= MIN_SITE_PIXELS pixels, shuffled with control sites
   (roofs of the same brightness that ACE did not flag), unlabelled. A person marks what each
   site is in satellite imagery. The key (detection or control) is written to the git-ignored
   data cache and regenerated by rerunning this script (seeded).

Usage (from /analysis):  uv run python make_ace_map.py
Outputs in docs/ace/: implantation.csv, ace_check.xlsx, ace_sites.kml, ace_viewer.html,
summary.json. Answers already in ace_check.xlsx are kept on a rerun.
"""

from __future__ import annotations

