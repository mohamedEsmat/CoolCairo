import numpy as np
import pandas as pd
from openpyxl import Workbook, load_workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.worksheet.datavalidation import DataValidation
from pyproj import Transformer
from scipy.ndimage import binary_dilation, label, minimum_filter

from coolcairo import detect
from coolcairo.buildings import footprint_mask
from coolcairo.config import DATA_DIR, REPO_ROOT, geobox_for, load_config
from coolcairo.library import maps_link, share_30m
from coolcairo.pipeline import FINE_RESOLUTION, build_blocks, load_enmap, load_lst

OUT = REPO_ROOT / "docs" / "ace"
TARGET_ID = 14
FALSE_ALARM_PERCENTILE = 99.8   # Course notebook 14: about 0.2 % of background pixels.
MIN_SITE_PIXELS = 4
N_CONTROLS = 12
SEED = 46
ANSWERS = ["Metal roof", "Other roof", "Not a roof", "Mixed", "Can't tell"]
COLOURS = ["White", "Light grey", "Dark grey", "Blue", "Green", "Red / brown", "Other"]
FONT = "Arial"


def sites_from(mask: np.ndarray) -> list[np.ndarray]:
    """Connected groups (8-neighbour) of a 2-D mask, each as an (n, 2) array of row, col."""
    lab, n = label(mask, structure=np.ones((3, 3)))
    return [np.argwhere(lab == k) for k in range(1, n + 1)]


def control_sites(ok_centre: np.ndarray, n: int, rng: np.random.Generator) -> list[np.ndarray]:
    """`n` 3 x 3 blocks centred on randomly chosen allowed pixels, not overlapping."""
    picks, taken = [], np.zeros_like(ok_centre)
    for r, c in rng.permutation(np.argwhere(ok_centre)):
        if taken[r - 2:r + 3, c - 2:c + 3].any():
            continue
        taken[r - 2:r + 3, c - 2:c + 3] = True
        picks.append(np.array([(r + dr, c + dc) for dr in (-1, 0, 1) for dc in (-1, 0, 1)]))
        if len(picks) == n:
            break
    return picks


def _previous(path: object) -> dict[tuple, list]:
    if not path.exists():
        return {}
    ws = load_workbook(path)["Sites"]
    return {(ws.cell(r, 2).value, ws.cell(r, 3).value): [ws.cell(r, c).value for c in (5, 6, 7)]
            for r in range(2, ws.max_row + 1) if ws.cell(r, 2).value is not None}


def write_sheet(rows: list[dict], path: object) -> None:
    previous = _previous(path)
    wb = Workbook()
    ws = wb.active
    ws.title = "How to fill in"
    ws.column_dimensions["A"].width = 22
    ws.column_dimensions["B"].width = 90
    help_rows = [
        ("CoolCairo: roof-type check (ACE target detection)", None),
        ("", None),
        ("What this is", "Each row is a place in east Cairo outlined as red 30 m squares (EnMAP "
         "pixels). Some were picked by a target detector, some were not; the sheet does not say "
         "which, so please judge only what you see."),
        ("Time needed", f"About 30 minutes for {len(rows)} rows."),
        ("Steps", "1. Easiest: open ace_viewer.html (Esri imagery with the squares, Google "
         "satellite beside it; arrow keys move between sites). Or open ace_sites.kml in Google "
         "Earth.\n2. Choose in the yellow column what is under MOST of the red squares.\n"
         "3. If it is a roof, give its colour. Add a note if unsure "
         "(e.g. 'half roof, half yard')."),
        ("Metal roof", "Sheet metal, corrugated or ribbed panels, sheds, hangars, warehouses with "
         "visible panel lines or a metallic sheen. Often long straight ridges."),
        ("Other roof", "Concrete, plaster, membrane, tiles, or a flat roof with tanks and "
         "clutter."),
        ("Not a roof", "Paving, car parks, sports courts, bare ground, sand, construction site."),
        ("Mixed", "No single surface covers most of the squares."),
        ("Imagery date", "EnMAP scene: 22 April 2025. If the imagery shows a change since then, "
         "say so in the notes."),
    ]
    for r, (a, b) in enumerate(help_rows, start=1):
        ca = ws.cell(row=r, column=1, value=a)
        ca.font = Font(name=FONT, bold=True, size=14 if r == 1 else 11)
        ca.alignment = Alignment(vertical="top")
        if b is not None:
            cb = ws.cell(row=r, column=2, value=b)
            cb.font = Font(name=FONT)
            cb.alignment = Alignment(wrap_text=True, vertical="top")

    ws = wb.create_sheet("Sites")
    headers = ["#", "Latitude", "Longitude", "Open in Google Maps",
               "What is under most of the red squares?", "If a roof: colour", "Notes"]
    widths = [5, 11, 11, 20, 34, 18, 48]
    head_fill = PatternFill("solid", fgColor="2F5597")
    input_fill = PatternFill("solid", fgColor="FFF2CC")
    box = Border(*(Side(style="thin", color="BFBFBF"),) * 4)
    for col, (h, w) in enumerate(zip(headers, widths, strict=True), start=1):
        c = ws.cell(row=1, column=col, value=h)
        c.font = Font(name=FONT, bold=True, color="FFFFFF")
        c.fill = head_fill
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        ws.column_dimensions[c.column_letter].width = w
    ws.row_dimensions[1].height = 32
    answer = DataValidation(type="list", formula1='"' + ",".join(ANSWERS) + '"', allow_blank=True)
    colour = DataValidation(type="list", formula1='"' + ",".join(COLOURS) + '"', allow_blank=True)
    ws.add_data_validation(answer)
    ws.add_data_validation(colour)
    for row in rows:
        r = row["n"] + 1
        for col, v in enumerate([row["n"], row["lat"], row["lon"], "Open satellite view"], 1):
            ws.cell(row=r, column=col, value=v)
        ws.cell(row=r, column=4).hyperlink = maps_link(row["lat"], row["lon"])
        for col, v in zip((5, 6, 7), previous.get((row["lat"], row["lon"]), []), strict=False):
            ws.cell(row=r, column=col, value=v)
        for col in (5, 6, 7):
            ws.cell(row=r, column=col).fill = input_fill
        answer.add(ws.cell(row=r, column=5))
        colour.add(ws.cell(row=r, column=6))
        for col in range(1, 8):
            cell = ws.cell(row=r, column=col)
            cell.border = box
            cell.font = (Font(name=FONT, color="0563C1", underline="single") if col == 4
                         else Font(name=FONT))
    ws.freeze_panes = "A2"
    wb.save(path)


def write_kml(rows: list[dict], path: object) -> None:
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<kml xmlns="http://www.opengis.net/kml/2.2"><Document>',
           "<name>CoolCairo roof-type check (EnMAP 30 m pixels)</name>",
           '<Style id="px"><LineStyle><color>ff2d2dff</color><width>2</width></LineStyle>'
           "<PolyStyle><fill>0</fill></PolyStyle></Style>"]
    for row in rows:
        polys = "".join(
            "<Polygon><outerBoundaryIs><LinearRing><coordinates>"
            + " ".join(f"{lon:.7f},{lat:.7f},0" for lat, lon in ring)
            + "</coordinates></LinearRing></outerBoundaryIs></Polygon>" for ring in row["rings"])
        out.append(f"<Placemark><name>{row['n']}</name><styleUrl>#px</styleUrl>"
                   f"<MultiGeometry>{polys}</MultiGeometry></Placemark>")
    out.append("</Document></kml>")
    path.write_text("\n".join(out), encoding="utf-8")


def write_viewer(rows: list[dict], path: object) -> None:
    data = json.dumps([{"n": r["n"], "lat": r["lat"], "lon": r["lon"], "rings": r["rings"]}
                       for r in rows])
    path.write_text(VIEWER.replace("__DATA__", data), encoding="utf-8")


def main() -> None:
    cfg = load_config()
    refl = load_enmap(cfg)
    cube = refl.values
    nb, ny, nx = cube.shape
    finite = np.isfinite(cube).all(axis=0)

    cand = pd.read_csv(REPO_ROOT / "docs" / "spectral_library" / "candidates.csv").set_index("id")
    r0, c0 = int(cand.loc[TARGET_ID, "row"]), int(cand.loc[TARGET_ID, "col"])
    roof9 = np.stack([cube[:, r0 + dr, c0 + dc] for dr in (-1, 0, 1) for dc in (-1, 0, 1)])
    perm = np.random.default_rng(7).permutation(9)
    near_target = np.zeros((ny, nx), bool)
    near_target[r0 - 2:r0 + 3, c0 - 2:c0 + 3] = True
    background = cube[:, finite & ~near_target].T

    bench = detect.implantation(background, np.median(roof9[perm[:4]], axis=0), roof9[perm[4:]])
    OUT.mkdir(parents=True, exist_ok=True)
    bench.round(4).to_csv(OUT / "implantation.csv", index=False)
    print(bench.pivot(index="fraction", columns="detector",
                      values="detected_at_1pct_false_alarms").round(3).to_string())

    mu, ci = detect.background_stats(background)
    score = np.full((ny, nx), np.nan)
    score[finite] = detect.ace(cube[:, finite].T, np.median(roof9, axis=0), mu, ci)
    threshold = float(np.nanpercentile(score[finite & ~near_target], FALSE_ALARM_PERCENTILE))
    detected = np.nan_to_num(score) > threshold

    _, _, buildings = build_blocks(cfg)
    roof10 = footprint_mask(buildings, geobox_for(cfg, "model_aoi", FINE_RESOLUTION)).values
    roof = share_30m(roof10.astype(bool), (ny, nx))
    lst = load_lst(cfg).values
    bright = np.nanmean(cube, axis=0)

    sites = [s for s in sites_from(detected) if len(s) >= MIN_SITE_PIXELS]
    det_bright = bright[detected & (roof > 0.5)]
    lo, hi = np.percentile(det_bright, [10, 90])
    away = ~binary_dilation(detected, iterations=4)
    block_ok = (finite & (roof > 0.5) & away
                & (np.nan_to_num(score) < threshold / 2))   # Clearly not detected.
    block_ok = minimum_filter(block_ok.astype(np.uint8), size=3).astype(bool)  # Whole 3 x 3.
    ok = block_ok & (bright >= lo) & (bright <= hi)   # Centre as bright as the detected roofs.
    ok[[0, -1], :] = ok[:, [0, -1]] = False   # The 3 x 3 block must lie inside the grid.
    rng = np.random.default_rng(SEED)
    controls = control_sites(ok, N_CONTROLS, rng)
    print(f"control candidates: {int(ok.sum())} pixels -> {len(controls)} sites")

    to_wgs = Transformer.from_crs(cfg.crs, "EPSG:4326", always_xy=True)
    xs, ys = refl.x.values, refl.y.values

    def ring(r: int, c: int) -> list[list[float]]:
        x, y = xs[c], ys[r]
        corners = [(x - 15, y - 15), (x + 15, y - 15), (x + 15, y + 15), (x - 15, y + 15),
                   (x - 15, y - 15)]
        return [[round(la, 7), round(lo_, 7)] for lo_, la in
                (to_wgs.transform(cx, cy) for cx, cy in corners)]

    entries = [("detection", s) for s in sites] + [("control", s) for s in controls]
    order = rng.permutation(len(entries))
    rows, key = [], []
    for n, k in enumerate(order, start=1):
        kind, px = entries[k]
        lon, lat = to_wgs.transform(xs[px[:, 1]].mean(), ys[px[:, 0]].mean())
        rows.append({"n": n, "lat": round(lat, 6), "lon": round(lon, 6),
                     "rings": [ring(r, c) for r, c in px]})
        key.append({"n": n, "kind": kind, "pixels": len(px),
                    "ace_mean": float(np.nanmean(score[px[:, 0], px[:, 1]])),
                    "roof_share": float(roof[px[:, 0], px[:, 1]].mean()),
                    "lst_c": float(np.nanmean(lst[px[:, 0], px[:, 1]])),
                    "brightness": float(bright[px[:, 0], px[:, 1]].mean()),
                    "lat": round(lat, 6), "lon": round(lon, 6)})

    write_sheet(rows, OUT / "ace_check.xlsx")
    write_kml(rows, OUT / "ace_sites.kml")
    write_viewer(rows, OUT / "ace_viewer.html")
    (DATA_DIR / "ace").mkdir(parents=True, exist_ok=True)
    pd.DataFrame(key).to_csv(DATA_DIR / "ace" / "key.csv", index=False)

    on_roof = detected & (roof > 0.5)
    summary = {
        "target": f"library candidate #{TARGET_ID} ({cand.loc[TARGET_ID, 'lat']:.6f}, "
                  f"{cand.loc[TARGET_ID, 'lon']:.6f}), 3 x 3 pixels of one roof",
        "threshold_ace": round(threshold, 3),
        "detected_pixels": int(detected.sum()),
        "detected_share_on_roofs": round(float((roof[detected] > 0.5).mean()), 2),
        "sites_total": len(sites_from(detected)),
        "sites_in_sheet": len(sites), "controls_in_sheet": len(controls),
        "lst_detected_roofs_c": round(float(np.nanmean(lst[on_roof])), 2),
        "lst_all_roofs_c": round(float(np.nanmean(lst[roof > 0.5])), 2),
    }
    (OUT / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))


